#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

/*
 * Джойстик — аналоговый, две оси на потенциометрах, снимается через
 * ADC1 ESP32 (п. 3.2 требований: ось X — GPIO36 «VP», ось Y — GPIO39
 * «VN», питание 3.3 В без делителя, см. открытый вопрос №8).
 *
 * Кнопка «мёртвая рука» сюда НЕ входит: по требованиям это отдельная
 * кнопка на своём GPIO, электрически не связанная с джойстиком
 * (открытый вопрос №9) — см. buttons_hal_dead_man_held().
 *
 * Отдаёт показания, центрированные вокруг нуля: сырое значение ADC
 * минус центр оси (MODULE_JOYSTICK_ADC_CENTER_*). Масштаб полного хода
 * задан MODULE_JOYSTICK_RAW_FULL_SCALE — обе константы подлежат
 * калибровке на стенде (Приложение Б, пп. 3 и 5).
 */

typedef struct {
    int16_t x; /* центрировано: 0 — нейтраль */
    int16_t y;
} joystick_adc_sample_t;

/* Чистое преобразование сырых отсчётов ADC в центрированные значения —
 * тестируется на хосте. */
void joystick_adc_center(int raw_x, int raw_y, joystick_adc_sample_t *out);

/* ---- HAL (ESP-IDF) ---- */

esp_err_t joystick_adc_hal_init(void);

/* Один цикл чтения обеих осей. ESP_OK и *out заполнен — успех. */
esp_err_t joystick_adc_hal_read(joystick_adc_sample_t *out);

/* Число подряд идущих неудачных чтений ADC. Учитываются только ошибки,
 * которые вернул драйвер: содержательный критерий отказа аналогового
 * джойстика (оборванный провод даёт формально валидный отсчёт) в
 * требованиях намеренно не определён — открытый вопрос №10, FR-37.1. */
uint32_t joystick_adc_hal_consecutive_failures(void);
