#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

/*
 * Джойстик — Wii Nunchuk по I2C (адрес 0x52), протокол без шифрования
 * (инициализация 0xF0 0x55 / 0xFB 0x00 — обходит устаревшую XOR-схему
 * кодирования данных, используется во всех современных клонах).
 *
 * Кнопка Z используется как «мёртвая рука» (FR-13) — на Nunchuk это
 * кнопка под указательным пальцем при естественном хвате, удобна для
 * удержания. Кнопка C в текущей версии требований не задействована.
 */

typedef struct {
    int16_t x; /* центрировано: примерно -128..127, 0 — нейтраль */
    int16_t y;
    bool btn_z; /* «мёртвая рука» */
    bool btn_c; /* резерв */
} nunchuk_sample_t;

/* Чистое декодирование 6 сырых байт ответа Nunchuk. Формат (без
 * шифрования): [0]=X, [1]=Y, [2..4]=accel (не используется),
 * [5] бит0=Z(0=нажата) бит1=C(0=нажата). Тестируется на хосте. */
void nunchuk_decode(const uint8_t raw[6], nunchuk_sample_t *out);

/* ---- HAL (ESP-IDF) ---- */

/* Инициализация шины I2C и хэндшейка Nunchuk (0xF0 0x55 / 0xFB 0x00). */
esp_err_t nunchuk_hal_init(void);

/* Один цикл "запрос чтения (0x00) -> пауза -> чтение 6 байт".
 * ESP_OK и *out заполнен — успех. Любая другая ошибка — транзакция не
 * удалась; HAL сам считает подряд идущие отказы (FR-37.1) и, при
 * признаках зависания шины, выполняет bus recovery (FR-37.2). */
esp_err_t nunchuk_hal_read(nunchuk_sample_t *out);

/* Текущее число подряд идущих неудачных транзакций — верхний уровень
 * логики сравнивает его с MODULE_I2C_FAIL_THRESHOLD (FR-37.1). */
uint32_t nunchuk_hal_consecutive_failures(void);
